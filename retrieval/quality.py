"""Load the failure logs (redacted) and write the data-quality report.

    python -m retrieval.quality [--logs 01b_failure_logs.jsonl]
                                [--out reports/retrieval_data_quality.md]

The report checks, from the data, each belief the brief states about the
logs, so the cleaning rules rest on evidence rather than on assumptions.
It is a pure function of the file: byte-identical on every run.
"""

import argparse
import json
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

from retrieval import clean

DEFAULT_LOGS = Path("01b_failure_logs.jsonl")
DEFAULT_OUT = Path("reports/retrieval_data_quality.md")
LONG_LOG = 70  # the brief: "some logs are 70+ lines"
_FIELDS = ("id", "team", "log", "resolution")


@dataclass(frozen=True)
class Record:
    """One failure log, already redacted. Nothing unredacted is ever kept."""

    id: str
    team: str
    log: str
    resolution: str  # "" when none was recorded
    redactions: int  # secrets replaced in this record, all fields


def load_records(path) -> tuple[list[Record], list[tuple[int, str]]]:
    """(records, [(line number, reason)] for the lines skipped).

    A line is skipped if it is not a JSON object, lacks a string field, has an
    empty log, or repeats an id. Blank lines are ignored. Redaction happens
    here, before a record exists, so no later step can see a secret.
    """
    records, malformed, seen = [], [], set()
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    for number, line in enumerate(lines, 1):
        if not line.strip():
            continue
        try:
            raw = json.loads(line)
        except json.JSONDecodeError as exc:
            malformed.append((number, f"not JSON ({exc.msg})"))
            continue
        if not isinstance(raw, dict):
            malformed.append((number, "not a JSON object"))
            continue
        bad = [f for f in _FIELDS if not isinstance(raw.get(f), str)]
        if bad:
            malformed.append((number, f"missing or non-string field: {', '.join(bad)}"))
            continue
        if not raw["log"].strip():
            malformed.append((number, "empty log"))
            continue
        if raw["id"] in seen:
            malformed.append((number, f"duplicate id {clean.redact(raw['id'])}"))
            continue
        seen.add(raw["id"])
        fields, total = {}, 0
        for f in ("team", "log", "resolution"):
            fields[f], n = clean.redact_count(raw[f])
            total += n
        records.append(Record(id=raw["id"], redactions=total, **fields))
    return records, malformed


def normalise_resolution(text: str) -> str:
    """The cause-group key: case and spacing do not make a different fix."""
    return " ".join(text.lower().split())


# --- markdown helpers -------------------------------------------------------


def _code(text: str) -> str:
    return "`" + text.replace("`", "'").replace("|", "\\|") + "`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _verdict(ok: bool) -> str:
    return "**confirmed**" if ok else "**not confirmed**"


# --- the report ----------------------------------------------------------------------


def build_report(path, noise_df: float = clean.DEFAULT_NOISE_DF) -> str:
    records, malformed = load_records(path)
    logs = [r.log for r in records]
    noise = clean.learn_noise(logs, noise_df)
    df = clean.template_df(logs)
    signal = {r.id: clean.signal_lines(r.log, noise) for r in records}
    raw_lines = {r.id: [x for x in r.log.splitlines() if x.strip()] for r in records}
    n = len(records)
    out = [
        "# Retrieval data quality",
        "",
        (
            f"Source: `{Path(path).name}`. Generated by `python -m retrieval.quality`; "
            "every number below is computed from the file. Text shown here is "
            "already redacted."
        ),
        "",
        "## Records",
        "",
        f"- records loaded: **{n}**",
        f"- malformed lines skipped: **{len(malformed)}**",
    ]
    out += [f"  - line {line}: {reason}" for line, reason in malformed]
    teams = Counter(r.team for r in records)
    out.append(
        "- records per team: " + ", ".join(f"{t} {c}" for t, c in sorted(teams.items()))
    )

    # --- redactions ---
    redacted = [r for r in records if r.redactions]
    out += [
        "",
        "## Redactions",
        "",
        (
            "Secrets are replaced by `[REDACTED]` in every stored field (team, log, "
            "resolution) as the file is read. Records not listed had 0."
        ),
        "",
        (
            f"- records with a redaction: **{len(redacted)}** of {n}; "
            f"redactions in total: **{sum(r.redactions for r in records)}**"
        ),
        "",
        "| id | redactions | redacted lines |",
        "|---|---|---|",
    ]
    for r in redacted:
        lines = [x.strip() for x in r.log.splitlines() if clean.REDACTED in x]
        out.append(
            f"| {r.id} | {r.redactions} | {'<br>'.join(_code(x) for x in lines)} |"
        )

    # --- raw vs signal ---
    counts_raw = [len(raw_lines[r.id]) for r in records]
    counts_sig = [len(signal[r.id]) for r in records]
    out += [
        "",
        "## Raw vs signal lines",
        "",
        "| | average | min | max |",
        "|---|---|---|---|",
        (
            f"| raw lines (non-blank) | {sum(counts_raw) / n:.2f} | {min(counts_raw)} "
            f"| {max(counts_raw)} |"
        ),
        f"| signal lines | {sum(counts_sig) / n:.2f} | {min(counts_sig)} | {max(counts_sig)} |",
        "",
        (f"Logs with {LONG_LOG}+ raw lines: {sum(c >= LONG_LOG for c in counts_raw)}."),
    ]

    # --- noise ---
    limit = noise_df * n
    out += [
        "",
        "## Learned noise templates",
        "",
        (
            f"NOISE_DF = {noise_df}: a template is noise if more than {noise_df:.0%} of "
            f"the {n} logs contain it (df > {limit:.2f}, so df >= {int(limit) + 1}). "
            f"Templates learned: **{len(noise)}**. Top 20 by df:"
        ),
        "",
        "| df | share | template |",
        "|---|---|---|",
    ]
    ranked = sorted(noise.items(), key=lambda kv: (-kv[1], kv[0]))
    out += [f"| {c} | {c / n:.0%} | {_code(t)} |" for t, c in ranked[:20]]
    # The risk of a learned filter: a cause common enough to cross the line
    # would be filtered as boilerplate. Flag noise that looks like an error.
    errorish = [t for t, _ in ranked
                if re.search(r"error|exception|fail|fatal|denied|killed|oom", t)]  # fmt: skip
    top_signal = max((c for t, c in df.items() if t not in noise), default=0)
    out += [
        "",
        (
            f"- noise templates that look like an error line: "
            f"{', '.join(_code(t) for t in errorish) if errorish else 'none'}"
        ),
        (
            f"- the most common NON-noise template is in {top_signal} logs "
            f"(the line is at {int(limit) + 1}), so the margin is "
            f"{int(limit) + 1 - top_signal} logs."
        ),
    ]

    # --- beliefs ---
    groups = defaultdict(list)
    for r in records:
        if r.resolution.strip():
            groups[normalise_resolution(r.resolution)].append(r)
    out += ["", "## Beliefs", ""]

    # 1. one meaningful line among boilerplate
    per_log = Counter(counts_sig)
    not_one = [r for r in records if len(signal[r.id]) != 1]
    out += [
        "### 1. Each log has ONE meaningful error line among repeated boilerplate",
        "",
        f"{_verdict(not not_one)} as stated. Signal lines per log after the "
        "learned filter: "
        + ", ".join(f"{k} line(s): {v} logs" for k, v in sorted(per_log.items()))
        + f". Boilerplate is real: {len(noise)} templates each appear in more than "
        f"{noise_df:.0%} of logs; {sum(c >= LONG_LOG for c in counts_raw)} logs have "
        f"{LONG_LOG}+ lines (max {max(counts_raw)}).",
        "",
    ]
    if not_one:
        out += ["Logs with more than one signal line:", "",
                "| id | signal lines |", "|---|---|"]  # fmt: skip
        out += [
            f"| {r.id} | {'<br>'.join(_code(x) for x in signal[r.id])} |"
            for r in not_one
        ]
        out.append("")

    # 2. same cause, same resolution, different wording
    sizes = sorted((len(m) for m in groups.values()), reverse=True)
    varied = {k: len({clean.template(x) for r in m for x in signal[r.id]})
              for k, m in groups.items()}  # fmt: skip
    multi = [k for k, m in groups.items() if len(m) > 1]
    out += [
        "### 2. Logs sharing a cause share the resolution text, with different wording",
        "",
        f"{_verdict(all(varied[k] > 1 for k in multi))} for the wording. "
        f"{len(groups)} distinct non-empty resolutions; group sizes {sizes}. "
        "In every group of 2+ logs, the members' signal lines have "
        "more than one distinct template (wording differs, not just numbers): "
        + ", ".join(
            str(varied[k]) for k in sorted(multi, key=lambda k: (-len(groups[k]), k))
        )
        + ". That logs sharing a resolution share a cause is the dataset's "
        "definition and cannot be checked further here. Signal lines per "
        "group are listed at the end.",
        "",
    ]

    # 3. empty resolutions
    empty = [r for r in records if not r.resolution.strip()]
    out += [
        "### 3. Some logs have an EMPTY resolution",
        "",
        f"{_verdict(bool(empty))}: {len(empty)} logs.",
        "",
        "| id | team | signal lines |",
        "|---|---|---|",
    ]
    out += [f"| {r.id} | {r.team} | {'<br>'.join(_code(x) for x in signal[r.id])} |"
            for r in empty]  # fmt: skip

    # 4. identical text, conflicting resolutions
    by_log, by_signal = defaultdict(list), defaultdict(list)
    for r in records:
        by_log[r.log].append(r)
        by_signal["\n".join(signal[r.id])].append(r)

    def conflicts(index):
        return [m for m in index.values()
                if len({normalise_resolution(r.resolution) for r in m}) > 1]  # fmt: skip

    raw_conflicts, signal_conflicts = conflicts(by_log), conflicts(by_signal)
    out += [
        "",
        "### 4. Two logs have identical text but conflicting resolutions",
        "",
        (
            f"{_verdict(len(raw_conflicts) == 1 and len(raw_conflicts[0]) == 2)}: "
            f"{len(raw_conflicts)} set(s) of byte-identical logs with different "
            f"resolutions; {len(signal_conflicts)} set(s) with identical SIGNAL text "
            "and different resolutions (what sub-step C records as a conflict)."
        ),
        "",
        "| ids | identical | resolutions |",
        "|---|---|---|",
    ]
    for m in signal_conflicts:
        same = "raw text" if len({r.log for r in m}) == 1 else "signal text only"
        res = "<br>".join(f"{r.id}: {_cell(r.resolution) or '(empty)'}" for r in m)
        out.append(f"| {', '.join(r.id for r in m)} | {same} | {res} |")

    # 5. fake secrets
    left = sum(clean.redact_count(f)[1] for r in records
               for f in (r.team, r.log, r.resolution))  # fmt: skip
    redacted_signal = [
        (r, x) for r in records for x in signal[r.id] if clean.REDACTED in x
    ]
    out += [
        "",
        "### 5. Several logs contain fake secrets",
        "",
        (
            f"{_verdict(bool(redacted))}: {len(redacted)} records, "
            f"{sum(r.redactions for r in records)} redactions (table above). Running "
            f"redact() again on the stored text finds {left} more, so none is left in a "
            "form the patterns know."
        ),
        "",
        (
            f"**Finding:** {len(redacted_signal)} SIGNAL lines contain `[REDACTED]`. "
            "After redaction these lines are identical across the logs that had a "
            "secret, but appear in too few logs to be learned as noise, so they "
            "survive the filter and make otherwise unrelated logs look alike:"
        ),
        "",
        "| id | resolution | signal line |",
        "|---|---|---|",
    ]
    out += [f"| {r.id} | {_cell(r.resolution) or '(empty)'} | {_code(x)} |"
            for r, x in redacted_signal]  # fmt: skip

    # --- appendix ---
    out += _groups_section(path)
    out += ["", "## Appendix: signal lines by resolution group", ""]
    for key in sorted(groups, key=lambda k: (-len(groups[k]), k)):
        members = groups[key]
        out += [f"**{_cell(members[0].resolution)}** ({len(members)})", ""]
        out += [
            f"- {r.id}: " + " / ".join(_code(x) for x in signal[r.id]) for r in members
        ]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _groups_section(path) -> list[str]:
    """Step 6 of ingestion: the cause groups the index actually built."""
    from retrieval.index import build_index  # index imports this module

    idx = build_index(path)
    p = idx.params
    out = [
        "",
        "## Cause groups (index)",
        "",
        (
            f"Built by `retrieval.index.build_index` with backend **{idx.backend}**; "
            f"W_DENSE={p.w_dense}, LEX_K={p.lex_k}, ASSIGN_MIN={p.assign_min}. "
            "Logs are grouped by normalised resolution text (case and spacing "
            "ignored)."
        ),
        "",
        "| group | logs | recorded | inferred | resolution |",
        "|---|---|---|---|---|",
    ]
    for g in idx.groups:
        count = Counter(idx.status[m] for m in g.members)
        out.append(
            f"| {g.id} | {len(g.members)} | {count['recorded']} | "
            f"{count['inferred']} | {_cell(g.resolution) or '(none)'} |"
        )
    out += [
        "",
        "### Inferred resolutions",
        "",
        (
            "Scores compare the log's signal lines with each recorded group's "
            "signal lines only (best member, hybrid score); resolution text is "
            "not used as evidence. An empty resolution joins its best group if "
            f"that score is at least ASSIGN_MIN={p.assign_min}. Its fix is "
            "inferred only if that is the one group at or above ASSIGN_MIN; with "
            "two or more it is ambiguous (status `none`, no fix shown); with none "
            "it stays a singleton (SPEC_DECISIONS #17)."
        ),
        "",
        "| id | status | group | decision | groups at or above ASSIGN_MIN | signal lines |",
        "|---|---|---|---|---|---|",
    ]
    for r in idx.records:
        if r.resolution.strip():
            continue
        found = idx.candidates(r.id)
        decision = {0: "below ASSIGN_MIN", 1: "inferred"}.get(len(found), "ambiguous")
        listed = ", ".join(f"{g} {s:.3f}" for g, s in found) or "—"
        lines = "<br>".join(_code(x) for x in idx.signal[r.id])
        out.append(
            f"| {r.id} | {idx.status[r.id]} | {idx.group_of[r.id]} | {decision} | "
            f"{listed} | {lines} |"
        )
    out += ["", "### Conflicts", ""]
    if not idx.conflicts:
        out.append("None.")
    for c in idx.conflicts:
        res = "; ".join(
            f"{i}: {_cell(x)}" for i, x in zip(c.ids, c.resolutions, strict=True)
        )
        out.append(
            f"- {', '.join(c.ids)} have identical signal text but different "
            f"resolutions ({res}). Each keeps its own; search results carry the "
            'note "conflicting resolutions recorded for an identical log".'
        )
    return out


def write_report(path, out, noise_df: float = clean.DEFAULT_NOISE_DF) -> str:
    text = build_report(path, noise_df)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(text, encoding="utf-8")
    return text


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--logs", type=Path, default=DEFAULT_LOGS)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--noise-df", type=float, default=clean.DEFAULT_NOISE_DF)
    args = parser.parse_args(argv)
    write_report(args.logs, args.out, args.noise_df)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
